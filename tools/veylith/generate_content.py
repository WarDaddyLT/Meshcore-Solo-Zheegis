"""Compile authoritative GDD content, stat gates and descriptions into ROM tables."""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parents[2]
text=(root/'docs/design/Veylith_Arena_GDD_v1.0.md').read_text()
elements=['Ember','Tide','Thorn','Stone','Spark'];families=[];moves={};notes={}
for line in text.splitlines():
 if not line.startswith('|'):continue
 cols=[x.strip() for x in line.strip('|').split('|')]
 if len(cols)==7 and re.fullmatch(r'\d{2}',cols[0]) and '/' in cols[1]:
  first,second=cols[1].split('/');families.append({'id':int(cols[0]),'types':[elements.index(first),elements.index(second)],'names':cols[2:5],'base':list(map(int,cols[5].split('/')))})
 elif len(cols)==3 and re.fullmatch(r'S\d{2}',cols[0]):
  notes[int(cols[0][1:])]={'name':cols[1],'description':cols[2]}
 elif cols[0].isdigit() and 1<=int(cols[0])<=80:
  i=int(cols[0])
  if i<=40 and len(cols)==10:
   moves[i]={'name':cols[1],'element':(i-1)//8,'role':cols[2],'power':int(cols[3]),'energy':int(cols[4]),'cooldown':int(cols[5]),'target':'EN','level':int(cols[6]),'effectText':cols[7]}
  elif 41<=i<=65 and len(cols)==11:
   moves[i]={'name':cols[1],'element':5,'role':cols[2],'power':int(cols[3]),'energy':int(cols[4]),'cooldown':int(cols[5]),'target':cols[6],'level':int(cols[7]),'effectText':cols[8]}
  elif i>=66 and len(cols)==11:
   moves[i]={'name':cols[1],'element':elements.index(cols[2]),'role':cols[3],'power':0,'energy':int(cols[4]),'cooldown':int(cols[5]),'target':cols[6],'level':int(cols[7]),'effectText':cols[8]}
  else:continue
  gates=[] if cols[-2]=='None' else [tuple(part.strip().split('>=')) for part in cols[-2].split('&')]
  assert len(gates)<=2
  moves[i]['gates']=[(stat,int(value)) for stat,value in gates]
  moves[i]['description']=cols[-1]
assert len(families)==20 and len({tuple(f['types']) for f in families})==20 and len({n for f in families for n in f['names']})==60
assert set(moves)==set(range(1,81)) and set(notes)==set(range(1,61))
for f in families:
 for stage,name in enumerate(f['names']):assert notes[(f['id']-1)*3+stage+1]['name']==name
for m in moves.values():
 assert m['description'] and len(m['description'])<=70
 assert m['effectText'] and len(m['effectText'])<=100
 for stat,value in m['gates']:assert stat in ['HP','ATK','DEF','FOC','WARD','SPD'] and 1<=value<=400
effects={}
def effect(ids,name,amount=0,chance=0):
 for i in ids:effects[i]=(name,amount,chance)
effect([1,9,17,25,33,41],'NONE')
for i,p in [(2,10),(4,20)]:effect([i],'BURN_PROC',0,p)
effect([3,11,19,27,35],'PIERCE_DEF',20);effect([16],'PIERCE_WARD',30);effect([28],'PIERCE_WARD',25)
effect([5],'ATK_DOWN',15);effect([6],'BURN_BARE')
for i,p in [(7,35),(12,10),(15,40),(22,15),(61,35)]:effect([i],'DRAIN_SELF',p)
effect([8],'SHIELD_EXTRA',20);effect([10],'SLOW_PROC',20,10);effect([13,37],'SLOW',20);effect([14],'WET_MARK')
for i,p in [(18,10),(24,30)]:effect([i],'ROOT_PROC',0,p)
effect([20],'POISON_PROC',0,20);effect([21],'POISON_BARE');effect([23],'DRAIN_ALLY',25);effect([26],'DEF_DOWN_PROC',15,10);effect([29],'DEF_DOWN',15);effect([30],'ROOT_HIT')
effect([31],'SHIELD_ON_HIT',25);effect([32],'SHIELD_BYPASS',30)
for i,p in [(34,10),(36,20)]:effect([i],'SHOCK_PROC',0,p)
effect([38],'CHARGE_MARK',10,20);effect([39],'ENERGY_HIT',2);effect([40],'NEXT_PRIORITY',1)
for i,p in [(42,25),(45,30),(51,12)]:effect([i],'HEAL_PERCENT',p)
effect([43],'GUARD_HIT',50);effect([44],'ENERGY_RESTORE',3)
for i,p in [(46,18),(58,12),(69,10),(72,22),(75,25),(76,15)]:effect([i],'SHIELD_PERCENT',p)
effect([47],'ATK_TEAM',15);effect([48],'ATK_WEAKEN',20);effect([49,52],'CLEAN_ONE');effect([50],'COUNTER_DEALT',30);effect([53],'DEF_WARD_WEAKEN',20);effect([54],'SPD_TEAM',15);effect([55],'TRANSFER_HP',20);effect([56],'ANCHOR_SOUL');effect([57],'REVIVE_ONE',30);effect([59,74],'CLEAN_TEAM');effect([60],'FOC_TEAM',15);effect([62],'PRIORITY_SHIELD',8);effect([63],'SILENCE',2);effect([64],'MASS_REVIVE',15);effect([65],'ANTHEM',20);effect([66],'HEAT_MANTLE',22,20);effect([67],'ATK_TEAM',20);effect([68],'HEAL_BURN',25);effect([70],'HEAL_TEAM_BURN',14);effect([71],'REVIVE_ONE',25);effect([73],'REGEN_TEAM',8);effect([77],'COUNTER_BLOCKED',35);effect([78],'SPD_SELF',25);effect([79],'FLASH_RELAY',2);effect([80],'FOC_TEAM',20)
assert set(effects)==set(moves)
q=lambda s:json.dumps(s,ensure_ascii=True)
lines=['// Generated by tools/veylith/generate_content.py; edit the authoritative GDD.','#include "Content.h"','namespace veylith {','const char* const elementNames[]={"Ember","Tide","Thorn","Stone","Spark","Neutral"};','const char* const statNames[]={"HP","ATK","DEF","FOC","WARD","SPD"};','const char* const roleNames[]={"PHY","ARC","HEAL","GUARD","BUFF","DEBUFF","CLEAN","REVIVE"};','const char* const targetNames[]={"Enemy","Self","Bench ally","Fainted ally","Team","Fainted team"};','const Family families[20]={']
for f in families:
 descriptions=[notes[(f['id']-1)*3+stage+1]['description'] for stage in range(3)]
 lines.append('  {{'+','.join(q(n) for n in f['names'])+'},'+','.join(map(str,f['types']))+',{'+','.join(map(str,f['base']))+'},{'+','.join(map(q,descriptions))+'}},')
lines+=['};','const Move moves[80]={']
for i in range(1,81):
 m=moves[i];e,amount,chance=effects[i];gates=m['gates']+[('HP',0)]*(2-len(m['gates']))
 fields=[q(m['name']),q(m['description']),q(m['effectText']),str(m['element']),m['role'],str(m['power']),str(m['energy']),str(m['cooldown']),m['target'],str(m['level']),e,str(amount),str(chance),'{'+','.join(s for s,v in gates)+'}','{'+','.join(str(v) for s,v in gates)+'}']
 lines.append('  {'+','.join(fields)+'},')
roles=['PHY','ARC','HEAL','GUARD','BUFF','DEBUFF','CLEAN','REVIVE']
order=sorted(moves,key=lambda i:(roles.index(moves[i]['role']),moves[i]['level'],i))
lines+=['};','const uint8_t moveOrder[80]={'+','.join(map(str,order))+'};','}']
output=root/'src/games/veylith/Content.cpp';data='\n'.join(lines)+'\n'
if '--check' in sys.argv:assert output.read_text()==data,'Content.cpp is stale; run generate_content.py'
else:output.write_text(data)
print('Validated 20 families, 60 form descriptions, 80 move descriptions/stat gates and typed effects from the GDD.')
