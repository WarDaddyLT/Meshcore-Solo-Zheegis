"""Validate the supplied v2 art and compile it for the L1 OLED's MSB-first bitmap renderer.

Uses only the Python standard library. No resampling, mirroring or extra RAM atlas.
"""
from pathlib import Path
import json
import re
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parents[2]
PACK = ROOT / 'docs/design/Veylith_Arena_Assets_v2'


def bitmap(path, width, height):
    raw = path.read_bytes()
    assert raw[:8] == b'\x89PNG\r\n\x1a\n', path
    pos, compressed, header = 8, bytearray(), None
    while pos < len(raw):
        size = struct.unpack('>I', raw[pos:pos + 4])[0]
        kind, data = raw[pos + 4:pos + 8], raw[pos + 8:pos + 8 + size]
        assert zlib.crc32(kind + data) == struct.unpack('>I', raw[pos + 8 + size:pos + 12 + size])[0], path
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', data)
        if kind == b'IDAT':
            compressed.extend(data)
        pos += size + 12
    assert header == (width, height, 1, 0, 0, 0, 0), (path, header)
    scan = zlib.decompress(compressed)
    stride = (width + 7) // 8
    assert len(scan) == (stride + 1) * height, path
    out, previous = bytearray(), bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        mode, row = scan[start], bytearray(scan[start + 1:start + 1 + stride])
        assert mode < 5, path
        for x in range(stride):
            left, above, corner = row[x - 1] if x else 0, previous[x], previous[x - 1] if x else 0
            estimate = left + above - corner
            distances = [abs(estimate - value) for value in (left, above, corner)]
            paeth = (left, above, corner)[distances.index(min(distances))]
            row[x] = (row[x] + (0, left, above, (left + above) // 2, paeth)[mode]) & 255
        out.extend(row)
        previous = row
    return bytes(out)


def compile_assets():
    manifest = json.loads((PACK / 'manifest.json').read_text())
    assert manifest['version'] == '2.1'
    gdd = (ROOT / 'docs/design/Veylith_Arena_GDD_v1.0.md').read_text()
    family_rows = [line for line in gdd.splitlines() if re.match(r'\|\s*\d+\s*\|', line)]
    # Content generator owns the authoritative names; compare the generated table.
    content = (ROOT / 'src/games/veylith/Content.cpp').read_text()
    names = re.findall(r'\{\{"([^"]+)","([^"]+)","([^"]+)"\}', content)
    assert len(names) == 20 and family_rows
    creatures, minis = bytearray(), bytearray()
    species = manifest['species']
    assert len(species) == 60
    for i, entry in enumerate(species):
        assert entry['species_id'] == i + 1 and entry['family_id'] == i // 3 + 1 and entry['stage'] == i % 3 + 1
        assert entry['name'] == names[i // 3][i % 3], entry
        front = bitmap(PACK / entry['front'], 32, 32)
        assert 'back' not in entry
        creatures.extend(front)
        minis.extend(bitmap(PACK / f'trainer/species_{i + 1:02}_icon_16px.png', 16, 16))
    assert len(creatures) == 7680 and not list((PACK / 'creatures').glob('*_back.png'))
    portraits = b''.join(bitmap(PACK / f'trainer/trainer_{pose}_24x32.png', 24, 32) for pose in ('idle', 'train', 'level_up', 'ready'))
    icons = b''.join(bitmap(PACK / f'ui_icons/{name}_8x8.png', 8, 8) for name in manifest['trainer']['icons_8x8'])
    progress = b''.join(bitmap(PACK / path, 32, 7) for path in manifest['trainer']['level_progress_frames'])
    arrays = [('creatureArt', creatures), ('miniArt', minis), ('trainerArt', portraits), ('iconArt', icons), ('progressArt', progress)]
    header = '#pragma once\n#include <stdint.h>\nnamespace veylith {\n'
    source = '// Generated by tools/veylith/generate_assets.py from the supplied v2 pack.\n#include "Assets.h"\nnamespace veylith {\n'
    for name, values in arrays:
        header += f'extern const uint8_t {name}[{len(values)}];\n'
        source += f'const uint8_t {name}[{len(values)}] = {{\n'
        for offset in range(0, len(values), 24):
            source += '  ' + ','.join(f'0x{v:02x}' for v in values[offset:offset + 24]) + ',\n'
        source += '};\n'
    header += '''inline const uint8_t* sprite(unsigned family,unsigned stage) {
  return creatureArt+((family<20?family:0)*3+(stage<3?stage:0))*128;
}
inline const uint8_t* mini(unsigned family,unsigned stage) {
  return miniArt+((family<20?family:0)*3+(stage<3?stage:0))*32;
}
}
'''
    source += '}\n'
    for name, data in [('Assets.h',header),('Assets.cpp',source)]:
        output = ROOT / 'src/games/veylith' / name
        if '--check' in sys.argv:
            assert output.read_text() == data, f'{name} is stale; run generate_assets.py'
        else:
            output.write_text(data)
    print(f'Validated 60 front sprites / runtime horizontal player mirroring; {sum(len(v) for _, v in arrays)} flash bytes; pixel-exact MSB-first data.')


if __name__ == '__main__':
    compile_assets()
